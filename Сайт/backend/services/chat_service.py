    GREETINGS = ["привет", "здравствуй", "добрый день", "добрый вечер", "хай", "hello"]

    def get_response(self, message: str, user_name: str = "") -> str:
        lower = message.lower().strip()

        if any(g in lower for g in self.GREETINGS):
            name_part = f", {user_name}" if user_name else ""
            return (
                f"Здравствуйте{name_part}! Я готов помочь с вопросами о кредитах, "
                f"скоринге, кредитной истории и финансовых продуктах. Что вас интересует?"
            )

        if "спасибо" in lower or "благодар" in lower:
            return "Пожалуйста! Если будут ещё вопросы — обращайтесь. Удачи с кредитом!"

        for keyword, response in self.KEYWORDS.items():
            if keyword in lower:
                return response

        if "как" in lower and ("улучш" in lower or "повыш" in lower):
            return (
                "Чтобы повысить шансы на одобрение кредита:\n"
                "1. Закройте просрочки и текущие задолженности\n"
                "2. Снизьте долговую нагрузку (платежи < 40% дохода)\n"
                "3. Подтвердите стабильный доход (2-НДФЛ)\n"
                "4. Не подавайте заявки в несколько банков одновременно\n"
                "5. Проверьте кредитную историю на ошибки"
            )

        if "сколько" in lower or "какую сумм" in lower:
            return (
                "Рекомендованная сумма зависит от вашего дохода и кредитного рейтинга. "
                "Как правило, ежемесячный платёж не должен превышать 40% дохода. "
                "Пройдите анализ в разделе «Новый анализ», чтобы получить персональную рекомендацию."
            )

        return (
            "Интересный вопрос! Я специализируюсь на темах: кредиты, скоринг, "
            "кредитная история, ставки, документы, ипотека и рефинансирование. "
            "Попробуйте переформулировать вопрос или спросите о чём-то из этого списка."
        )

